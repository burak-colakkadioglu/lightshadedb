#[derive(Clone, Debug)]

pub struct GenerateOptions {
    pub row_types: BTreeMap<String, String>,
    pub migrations: BTreeMap<String, MigrationTable>,
    pub emit_row_structs: bool,
    pub emit_inner_attributes: bool,
    pub public_db: bool,
}

#[derive(Clone, Debug, Default)]
pub struct MigrationTable {
    pub stored_name: String,
    pub fields: BTreeMap<String, MigrationField>,
}

#[derive(Clone, Debug, Default)]
pub struct MigrationField {
    pub stored_name: String,
    pub convert: Option<(crate::ir::Ty, String)>,
}

impl Default for GenerateOptions {
    fn default() -> Self {
        Self {
            row_types: BTreeMap::new(),
            migrations: BTreeMap::new(),
            emit_row_structs: true,
            emit_inner_attributes: true,
            public_db: false,
        }
    }
}

thread_local! {
    static ACTIVE_ROW_TYPES: RefCell<BTreeMap<String, String>> = const { RefCell::new(BTreeMap::new()) };
    static ACTIVE_MIGRATIONS: RefCell<BTreeMap<String, MigrationTable>> = const { RefCell::new(BTreeMap::new()) };
}

pub fn generate(workload: &Workload) -> Result<String, String> {
    generate_library(workload)
}

pub fn generate_library(workload: &Workload) -> Result<String, String> {
    generate_library_with(workload, &GenerateOptions::default())
}

pub fn generate_library_with(
    workload: &Workload,
    options: &GenerateOptions,
) -> Result<String, String> {
    let previous = ACTIVE_ROW_TYPES.with(|types| types.replace(options.row_types.clone()));
    let previous_migrations =
        ACTIVE_MIGRATIONS.with(|mappings| mappings.replace(options.migrations.clone()));
    let result = generate_library_impl(workload, options);
    ACTIVE_ROW_TYPES.with(|types| *types.borrow_mut() = previous);
    ACTIVE_MIGRATIONS.with(|mappings| *mappings.borrow_mut() = previous_migrations);
    result
}

fn generate_library_impl(workload: &Workload, options: &GenerateOptions) -> Result<String, String> {
    let plan = build_plan(workload)?;
    let mut out = String::new();

    writeln!(out, "// Generated by Lightshade DB. Do not edit by hand.").unwrap();
    if options.emit_inner_attributes {
        writeln!(out, "#![allow(dead_code, non_snake_case, non_camel_case_types, unused_imports, unused_mut, unused_parens, unused_variables)]").unwrap();
    }
    writeln!(out, "use std::cmp::Reverse;").unwrap();
    writeln!(out, "use std::collections::BTreeMap;").unwrap();
    writeln!(out, "use std::fs::{{self, File, OpenOptions}};").unwrap();
    writeln!(out, "use std::io::{{self, Read, Seek, SeekFrom, Write}};").unwrap();
    writeln!(out, "use std::path::{{Path, PathBuf}};").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "const __LS_WORKLOAD: u64 = 0x{:016x};",
        workload_fingerprint(workload)
    )
    .unwrap();
    writeln!(
        out,
        "const __LS_SCHEMA: u64 = {}u64;",
        schema_fingerprint(workload)
    )
    .unwrap();
    out.push_str(PERSISTENCE_RUNTIME);
    out.push_str(ADMIN_RUNTIME);
    out.push_str(SLOW_RUNTIME);
    writeln!(out).unwrap();

    for (index, counter) in plan.counters.iter().enumerate() {
        let table = get_table(workload, &counter.table)?;
        let fields = eq_key_fields(&counter.eq, table)?;
        emit_key_struct(&mut out, &format!("Cnt{index}Key"), &fields, "e");
    }

    for (index, spec) in plan.indexes.iter().enumerate() {
        let table = get_table(workload, &spec.table)?;
        let eq_fields = eq_key_fields(&spec.eq, table)?;
        emit_key_struct(&mut out, &format!("Idx{index}Eq"), &eq_fields, "e");
        let inner_fields = index_inner_fields(spec, table)?;
        emit_key_struct(&mut out, &format!("Idx{index}Key"), &inner_fields, "f");
    }

    if options.emit_row_structs {
        for table in workload
            .tables
            .iter()
            .filter(|table| !workload.is_projection(&table.name))
        {
            writeln!(out, "#[derive(Clone, Debug)]").unwrap();
            writeln!(out, "struct {} {{", row_type(&table.name)).unwrap();
            for field in &table.fields {
                writeln!(out, "    {}: {},", field.name, field.ty.rust()).unwrap();
            }
            writeln!(out, "}}").unwrap();
            writeln!(out).unwrap();
        }
    }

    emit_table_storage(&mut out, workload)?;

    writeln!(
        out,
        "{}struct Db {{",
        if options.public_db { "pub " } else { "" }
    )
    .unwrap();
    for table in workload
        .tables
        .iter()
        .filter(|table| !workload.is_projection(&table.name))
    {
        writeln!(out, "    t_{}: Rows_{},", table.name, table.name).unwrap();
    }
    for (index, _) in plan.indexes.iter().enumerate() {
        writeln!(
            out,
            "    idx{index}: std::sync::RwLock<__LsIndex<Idx{index}Eq, Idx{index}Key>>,",
        )
        .unwrap();
    }
    for (index, _) in plan.counters.iter().enumerate() {
        writeln!(out, "    cnt{index}: BTreeMap<Cnt{index}Key, u64>,").unwrap();
    }
    writeln!(out, "    __ls_store: Option<__LsStore>,").unwrap();
    writeln!(out, "    __ls_versions: Vec<u64>,").unwrap();
    writeln!(out, "    __ls_lsn: u64,").unwrap();
    writeln!(out, "    __ls_effects: Vec<u8>,").unwrap();
    writeln!(out, "    __ls_in_transaction: bool,").unwrap();
    writeln!(out, "    __ls_memory_backup: Option<Vec<u8>>,").unwrap();
    writeln!(out, "    __ls_broken: Option<String>,").unwrap();
    writeln!(out, "    __ls_read_only: bool,").unwrap();
    writeln!(out, "    __ls_max_rows: u64,").unwrap();
    writeln!(out, "    __ls_max_wal_bytes: u64,").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "impl Db {{").unwrap();
    for (name, create) in [
        ("__ls_new", "Rows_{}::__ls_create_direct()?"),
        ("__ls_new_spilled", "Rows_{}::__ls_create(table_budget)?"),
    ] {
        writeln!(out, "    fn {name}() -> io::Result<Db> {{").unwrap();
        if name == "__ls_new_spilled" {
            writeln!(out, "        let budget = __ls_row_cache_budget();").unwrap();
            writeln!(
                out,
                "        let table_budget = if budget == 0 {{ 0 }} else {{ (budget / {}u64).max(1) }};",
                workload.tables.iter().filter(|table| !workload.is_projection(&table.name)).count().max(1)
            )
            .unwrap();
        }
        writeln!(out, "        Ok(Db {{").unwrap();
        for table in workload
            .tables
            .iter()
            .filter(|table| !workload.is_projection(&table.name))
        {
            writeln!(
                out,
                "            t_{}: {},",
                table.name,
                create.replace("{}", &table.name)
            )
            .unwrap();
        }
        for (index, _) in plan.indexes.iter().enumerate() {
            writeln!(
                out,
                "            idx{index}: std::sync::RwLock::new(__LsIndex::new()),"
            )
            .unwrap();
        }
        for (index, _) in plan.counters.iter().enumerate() {
            writeln!(out, "            cnt{index}: BTreeMap::new(),").unwrap();
        }
        writeln!(out, "            __ls_store: None,").unwrap();
        writeln!(
            out,
            "            __ls_versions: vec![0; {}],",
            workload
                .tables
                .iter()
                .filter(|table| !workload.is_projection(&table.name))
                .count()
        )
        .unwrap();
        writeln!(out, "            __ls_lsn: 0,").unwrap();
        writeln!(out, "            __ls_effects: Vec::new(),").unwrap();
        writeln!(out, "            __ls_in_transaction: false,").unwrap();
        writeln!(out, "            __ls_memory_backup: None,").unwrap();
        writeln!(out, "            __ls_broken: None,").unwrap();
        writeln!(out, "            __ls_read_only: false,").unwrap();
        writeln!(out, "            __ls_max_rows: __ls_row_quota(),").unwrap();
        writeln!(out, "            __ls_max_wal_bytes: __ls_wal_quota(),").unwrap();
        writeln!(out, "        }})").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out).unwrap();
    }

    emit_persistence_methods(&mut out, workload)?;
    emit_engine_accessors(&mut out, options);
    emit_admin_methods(&mut out, workload);
    emit_adopt(&mut out, workload, &plan);

    for table in workload
        .tables
        .iter()
        .filter(|table| !workload.is_projection(&table.name))
    {
        emit_maintenance(&mut out, workload, &plan, table)?;
    }

    emit_transaction_support(&mut out, workload, &plan)?;

    for operation in &workload.operations {
        match &operation.body {
            Body::Insert { .. } => emit_insert(&mut out, workload, &plan, operation)?,
            Body::Update { .. } => emit_update(&mut out, workload, &plan, operation)?,
            Body::Delete { .. } => emit_delete(&mut out, workload, &plan, operation)?,
            Body::Query { count: true, .. } => {
                emit_count_query(&mut out, workload, &plan, operation)?
            }
            Body::Query { .. } if is_advanced_query(&operation.body) => {
                emit_advanced_query(&mut out, workload, &plan, operation)?
            }
            Body::Query { .. } => emit_many_query(&mut out, workload, &plan, operation)?,
        }
        writeln!(out).unwrap();
    }

    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    Ok(out)
}

